object ThemeManager {
    private const val PREFS = "girassol_theme"
    private const val KEY_THEME = "film_theme"
    private val mutableSelected = MutableStateFlow(FilmTheme.PORTRA_400)
    val selected: StateFlow<FilmTheme> = mutableSelected.asStateFlow()
    @Volatile private var initialized = false

    @Synchronized
    fun initialize(context: Context) {
        if (initialized) return
        val saved = context.applicationContext
            .getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .getString(KEY_THEME, null)
        mutableSelected.value = FilmTheme.entries.firstOrNull { it.name == saved } ?: FilmTheme.PORTRA_400
        initialized = true
    }

    fun select(context: Context, theme: FilmTheme) {
        initialize(context)
        mutableSelected.value = theme
        context.applicationContext.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .edit().putString(KEY_THEME, theme.name).apply()
    }

    fun all(): List<FilmTheme> = FilmTheme.entries
}
